#!/usr/bin/env bash
# One command to bring the whole demo stack up after a reboot (or from cold). Idempotent: safe to re-run.
#
#   ./scripts/demo-up.sh                 bring everything up, then run the preflight
#   ./scripts/demo-up.sh --skip-firewall do not touch the libvirt/Docker firewall helper
#   ./scripts/demo-up.sh --no-build      reuse existing container images
#
# Order: libvirt networks -> Minikube (KVM2) -> compose (pool host, sshd, node exporter) -> provider VM
#        -> interLink tunnel + virtual kubelet -> Grafana access -> preflight.
# Requires: .demo-laptop.env (see .demo-laptop.env.example) and infrastructure/docker/.env (generated if missing).
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="$HOME/.local/bin:$HOME/.docker/cli-plugins:$PATH"
ENV_FILE="${DEMO_ENV_FILE:-$ROOT/.demo-laptop.env}"
[[ -f "$ENV_FILE" ]] || { echo "Missing $ENV_FILE (copy .demo-laptop.env.example first)." >&2; exit 1; }
set -a; source "$ENV_FILE"; set +a

SKIP_FW=0; BUILD=--build
for a in "$@"; do case "$a" in --skip-firewall) SKIP_FW=1 ;; --no-build) BUILD="" ;; -h|--help) sed -n 2,11p "$0"; exit 0 ;; esac; done

PROFILE="${MINIKUBE_PROFILE:-w3node-demo}"
STATE="${DEMO_STATE_DIR:-$HOME/.local/state/w3node}"
COMPOSE_DIR="$ROOT/infrastructure/docker"
TUNNEL_DIR="$STATE/tunnel"
PROVIDER_VM="${PROVIDER_VM_NAME:-w3node-provider}"
GRAFANA_PORT="${GRAFANA_LOCAL_PORT:-3000}"
mkdir -p "$STATE/pids" "$STATE/logs" "$TUNNEL_DIR/hostkeys"

T0=$SECONDS; STEP_T=$SECONDS
step() { printf '\n\033[1;36m[%3ss] %s\033[0m\n' "$((SECONDS - T0))" "$*"; STEP_T=$SECONDS; }
ok()   { printf '  \033[32mOK\033[0m %s\n' "$*"; }
warn() { printf '  \033[33mWARN\033[0m %s\n' "$*"; }
die()  { printf '  \033[31mFAIL\033[0m %s\n' "$*" >&2; exit 1; }
wait_for() {  # wait_for "<description>" <timeout-seconds> <command...>
  local what=$1 timeout=$2; shift 2
  local end=$((SECONDS + timeout))
  until "$@" >/dev/null 2>&1; do
    ((SECONDS < end)) || die "timed out after ${timeout}s waiting for: $what"
    sleep 3
  done
  ok "$what"
}
virsh_() { virsh -c qemu:///system "$@"; }
net_ip() { virsh_ net-dumpxml "$1" 2>/dev/null | sed -n "s/.*<ip address='\([0-9.]*\)'.*/\1/p" | head -1; }
dc() { docker compose -f "$COMPOSE_DIR/compose.yaml" --env-file "$COMPOSE_DIR/.env" "$@"; }

step "Preconditions"
docker info >/dev/null 2>&1 || die "Docker is not reachable (is the docker service/socket enabled?)."
docker compose version >/dev/null 2>&1 || die "docker compose plugin missing (expected in ~/.docker/cli-plugins)."
command -v minikube >/dev/null && command -v kubectl >/dev/null || die "minikube/kubectl not found in PATH."
virsh_ list >/dev/null 2>&1 || die "Cannot talk to libvirt (qemu:///system). Is your user in the libvirt group?"
ok "docker, compose, libvirt, minikube, kubectl"

step "Tunnel key (throwaway, restricted to forwarding to the plugin port)"
[[ -f "$TUNNEL_DIR/tunnel" ]] || { ssh-keygen -q -t ed25519 -N '' -C w3node-tunnel -f "$TUNNEL_DIR/tunnel"; ok "generated $TUNNEL_DIR/tunnel"; }
ok "key present"

step "libvirt networks"
for n in default "mk-$PROFILE"; do
  if virsh_ net-info "$n" >/dev/null 2>&1; then
    virsh_ net-info "$n" | grep -q 'Active: *yes' || virsh_ net-start "$n" >/dev/null && ok "network $n active"
  fi
done

step "Minikube ($PROFILE, ${MINIKUBE_DRIVER:-kvm2})"
minikube start -p "$PROFILE" --driver="${MINIKUBE_DRIVER:-kvm2}" --cpus="${MINIKUBE_CPUS:-2}" --memory="${MINIKUBE_MEMORY:-4096}" --disk-size="${MINIKUBE_DISK_SIZE:-20g}" >"$STATE/logs/minikube-start.log" 2>&1 \
  || { tail -15 "$STATE/logs/minikube-start.log" >&2; die "minikube start failed"; }
wait_for "Kubernetes node Ready" 180 kubectl --context "$PROFILE" wait --for=condition=Ready "node/$PROFILE" --timeout=5s

step "Firewall helper (libvirt VMs <-> Docker host)"
BRIDGE_IP="$(net_ip "mk-$PROFILE")"
[[ -n "$BRIDGE_IP" ]] || die "Could not read the Minikube bridge address from libvirt network mk-$PROFILE."
if ((SKIP_FW)); then warn "skipped (--skip-firewall)"
elif sudo nft list chain ip filter DOCKER-USER 2>/dev/null | grep -q w3node-libvirt && sudo firewall-cmd --zone=libvirt --list-rich-rules 2>/dev/null | grep -q 'port="5820"'; then
  ok "rules already applied"
else
  echo "  applying (needs sudo; runtime-only rules, see infrastructure/scripts/libvirt-docker-firewall.sh)"
  sudo "$ROOT/infrastructure/scripts/libvirt-docker-firewall.sh" apply
fi

step "Compose environment"
ENV_OUT="$COMPOSE_DIR/.env"
if [[ ! -f "$ENV_OUT" ]]; then
  REH="$ROOT/.sepolia-rehearsal.env"
  [[ -f "$REH" ]] || die "No $ENV_OUT and no $REH to derive it from. Create the .env (see infrastructure/docker/env.example)."
  # shellcheck disable=SC1090
  ( set -a; source "$REH"; set +a
    cat > "$ENV_OUT" <<ENVF
# Generated by scripts/demo-up.sh from the rehearsal env. Non-secret values only; never put private keys here.
RPC_URL=${SEPOLIA_RPC_URL}
CHAIN_ID=${CHAIN_ID:-11155111}
CONTRACT_ADDRESS=${CONTRACT_ADDRESS}
START_BLOCK=${START_BLOCK:-0}
CONFIRMATIONS=1
POOL_HOSTNAME=$(net_ip default)
POOL_MACHINE_NAME=$(hostname -s)
POOL_RUN_STARTD=true
ENVF
  )
  ok "generated $ENV_OUT"
fi
# values that depend on the live libvirt networks are (re)written each start
sed -i '/^METRICS_ADDR=/d;/^MINIKUBE_BRIDGE_IP=/d;/^LISTEN_ADDR=/d' "$ENV_OUT"
printf 'LISTEN_ADDR=127.0.0.1:8090\nMETRICS_ADDR=%s:9101\nMINIKUBE_BRIDGE_IP=%s\n' "$BRIDGE_IP" "$BRIDGE_IP" >> "$ENV_OUT"
export TUNNEL_DIR MINIKUBE_BRIDGE_IP="$BRIDGE_IP"
ok "pool address $(grep ^POOL_HOSTNAME "$ENV_OUT" | cut -d= -f2), Minikube bridge $BRIDGE_IP"

step "Containers (pool host, sshd, node exporter)"
dc up -d $BUILD >"$STATE/logs/compose-up.log" 2>&1 || { tail -20 "$STATE/logs/compose-up.log" >&2; die "docker compose up failed"; }
wait_for "HTCondor answering in the pool container" 150 docker exec w3pool condor_status
wait_for "marketplace UI on 127.0.0.1:8090" 90 curl -fs http://127.0.0.1:8090/healthz
wait_for "plugin on 127.0.0.1:4000" 90 curl -fs http://127.0.0.1:4000/system-info
wait_for "sshd on 127.0.0.1:${SSH_PORT:-2222}" 60 bash -c "exec 3<>/dev/tcp/127.0.0.1/${SSH_PORT:-2222}"
wait_for "host key published" 30 test -s "$TUNNEL_DIR/hostkeys/hostkey.txt"

step "Provider VM ($PROVIDER_VM)"
if virsh_ dominfo "$PROVIDER_VM" >/dev/null 2>&1; then
  virsh_ domstate "$PROVIDER_VM" | grep -q running || virsh_ start "$PROVIDER_VM" >/dev/null
  wait_for "provider VM registered in the pool" 240 bash -c "docker exec w3pool condor_status -af Machine | grep -qx '$PROVIDER_VM'"
else
  warn "VM $PROVIDER_VM not defined; create it with ./scripts/demo-laptop.sh provider-up (the local provider still works)"
fi

step "interLink (SSH tunnel + API + virtual kubelet)"
"$ROOT/scripts/demo-laptop.sh" connect >"$STATE/logs/connect.log" 2>&1 || { tail -15 "$STATE/logs/connect.log" >&2; die "connect failed (see $STATE/logs/connect.log)"; }
wait_for "virtual node interlink-node Ready" 120 bash -c "[[ \$(kubectl --context $PROFILE get node interlink-node -o jsonpath='{.status.conditions[?(@.type==\"Ready\")].status}') == True ]]"
wait_for "plugin reachable through the SSH tunnel" 30 curl -fs "http://127.0.0.1:${PLUGIN_LOCAL_PORT:-${PLUGIN_PORT:-4000}}/system-info"

step "Grafana"
wait_for "monitoring pods Ready" 240 kubectl --context "$PROFILE" -n monitoring wait --for=condition=Ready pod -l app.kubernetes.io/name=grafana --timeout=5s
if ! curl -fs -o /dev/null "http://127.0.0.1:$GRAFANA_PORT/login"; then
  nohup kubectl --context "$PROFILE" -n monitoring port-forward svc/w3node-observability-grafana "$GRAFANA_PORT:80" >"$STATE/logs/pf-grafana.log" 2>&1 &
  echo $! > "$STATE/pids/pf-grafana.pid"
fi
wait_for "Grafana at http://127.0.0.1:$GRAFANA_PORT" 60 curl -fs -o /dev/null "http://127.0.0.1:$GRAFANA_PORT/login"

step "Preflight"
"$ROOT/scripts/demo-preflight.sh" && printf '\n\033[1;32mDemo stack is up in %ss.\033[0m\n' "$((SECONDS - T0))"
